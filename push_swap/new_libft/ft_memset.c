#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	unsigned char	*temp;

	temp = (unsigned char *)s;
	while (n > 0)
	{
		temp[n - 1] = (unsigned char)c;
		n--;
	}
	return (s);
}
